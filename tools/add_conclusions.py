path = Path(__file__).resolve().parent.parent / "data" / "regulations.jsonl"
lines = path.read_text(encoding="utf-8").splitlines()
out = []
missing = []
for line in lines:
    if not line.strip():
        continue
    doc = json.loads(line)
    c = CONCLUSIONS.get(doc["id"])
    if not c:
        missing.append(doc["id"])
        c = doc["text"][:60] + "……"
    doc["conclusion"] = c
    out.append(json.dumps(doc, ensure_ascii=False))
path.write_text("\n".join(out) + "\n", encoding="utf-8")
print("updated", len(out), "missing", missing)
